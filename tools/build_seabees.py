"""Check the Seabee transcriptions and build records/seabees/seabees.json for site/seabees.html.

Inputs (hand-edited, the source of truth; columns in records/seabees/README.md): units.csv,
parts.csv, stations.csv, places.csv, voyages.csv (the ships between two stations) and
voyage_positions.csv (the positions they logged, so the page draws those legs along the logged
track); weather.csv is generated by tools/fetch_station_weather.py. projects/ holds the battalions' main
construction projects, one Markdown file each (front matter: place, part, dates and their basis, what was built,
sources; body: `## Built` and `## Afterwards`, the history snapshot, each paragraph cited and the Afterwards ones
labelled *Record.*, *Secondary.*, *Inference.* or *Not known.*), and also-at.md the other stations.

Each part of a battalion (parts.csv) is drawn as its own line: its own rows while it existed,
joined to its parent's place before it split off and after it ended. The battalion's own line
breaks where it was in parts.

Checks: every station has a known unit, a source and a citation that resolves (SOURCES.yml's
`match` patterns), a known `assumed` value, and a place with coordinates (or none); every part
has stations and every station's part is in parts.csv; no leg of a part's line is faster than
MAX_KM_PER_DAY (a troop transport, about 20 knots) unless the arriving row's note says it went by
train, and no ship faster than 22 knots between logged positions; each voyage starts and ends at
stations.

The pieces are functions, so a project that adds its own rows (a family's man and his discharge,
say) builds them the same way.

  uv run tools/build_seabees.py      # must report 0 problems
"""
import csv
import json
import math
import re
import sys
from datetime import date, datetime, timedelta

import yaml

from records import RECORDS

SEABEES = RECORDS / "seabees"
MAX_KM_PER_DAY = 900        # ~20 knots, a fast transport; rail across the US is slower
MAX_KNOTS = 22              # a ship between two logged positions
SOURCE_CODES = ("muster", "wardiary", "ncbhist", "bases", "mcsol")
VOYAGE_STATUS = ("confirmed", "partial", "planned", "ordered", "named", "not recorded")
ZONE_HOURS = {"I": 9, "K": 10, "L": 11, "M": 12, "Z": 0}   # zone letter -> hours ahead of GMT
ASSUMED = ("", "date", "place", "part")
ROLLS = {"190273312": "20th Battalion's muster rolls", "190327559": "79th Battalion's muster rolls"}
WEATHER_FIELDS = ["era5_tmax_c", "era5_tmin_c", "era5_precip_mm", "era5_wind_max_kn", "isd_station", "isd_name",
                  "isd_km", "isd_obs", "isd_tmax_c", "isd_tmin_c", "isd_wind_mean_kn", "isd_wind_max_kn",
                  "isd_precip_reports"]


def read_csv(path, label=None):
    with path.open(newline="") as f:
        return [dict(r, _file=label or path.name) for r in csv.DictReader(f)]


def parse_coord(text):
    """'25° 57' S' or '15-43N' / '145-15.5E' -> signed decimal degrees."""
    m = re.match(r"^\s*(\d+)\s*(?:°|-)\s*([\d.]+)\s*'?\s*([NSEW])\s*$", text)
    if not m:
        raise ValueError(text)
    v = int(m.group(1)) + float(m.group(2)) / 60
    return -v if m.group(3) in "SW" else v


def km(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (a["lat"], a["lon"], b["lat"], b["lon"]))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * 6371 * math.asin(math.sqrt(h))


def citation_links(problems, extra=None, cache=""):
    """cite -> {cite, url, label[, scan]} from SOURCES.yml's match/link. `extra(cite)` is tried first
    (a project's own sources); `scan` is the page's path in the cache, after `cache`."""
    sources = yaml.safe_load((RECORDS / "SOURCES.yml").read_text())
    titles = json.loads((RECORDS / "citations.json").read_text())   # catalog titles, by NAID
    pats = [(sid, s, re.compile(s["match"])) for sid, s in sources.items() if "match" in s]

    def link(cite):
        got = extra(cite) if extra else None
        if got:
            return got
        for sid, s, pat in pats:
            m = pat.match(cite)
            if not m:
                continue
            if sid == "url":
                label = ("Marines in the Central Solomons" if "USMC-M-CSol" in cite
                         else "Pacific Wrecks: Bau Island PT base" if "pacificwrecks" in cite
                         else "Bulkley, At Close Quarters, ch. 3" if "CloseQuarters/PT-3" in cite else cite)
                return {"cite": cite, "url": cite, "label": label}
            url = s["link"].format(None, *m.groups())
            if sid == "nara-catalog":
                rg, na, page = m.groups()
                roll = ROLLS.get(na) or re.sub(r"\s+-\s+War Diary,?", " war diary,", titles.get(na, {}).get("title", f"NARA {na}"))
                return {"cite": cite, "url": url, "label": f"{roll}, page {int(page)}",
                        "scan": f"{cache}nara/rg{rg}-{na}/p{int(page):04d}.jpg"}
            if sid == "ncbhist":
                n, page = m.groups()
                return {"cite": cite, "url": url, "label": f"{int(n)}th Battalion's history sheet (Seabee Museum), page {page}",
                        "scan": f"{cache}seabee-museum/ncb{n}/pages/p{int(page):03d}.jpg"}
            if sid == "bases":
                return {"cite": cite, "url": url, "label": f"Building the Navy's Bases, ch. {m.group(1)}"}
            return {"cite": cite, "url": url, "label": s.get("title", sid)}
        problems.append(f"citation doesn't resolve: {cite}")
        return {"cite": cite, "url": "", "label": cite}
    return link


def load_places(rows, problems):
    places = {}
    for r in rows:
        if not (r["lat"] and r["lon"]):
            problems.append(f"{r['_file']}: {r['place']} has no coordinates")
            continue
        places[r["place"]] = {"lat": float(r["lat"]), "lon": float(r["lon"]), "source": r["source"], "note": r["note"]}
    return places


def load_stations(stations, units, places, link, problems, sources=SOURCE_CODES, own=lambda r: False):
    """The station rows, numbered in order (`id`); `own(r)` marks a project's own rows (`family`)."""
    rows = []
    for i, r in enumerate(stations):
        where = f"{r['_file']}: {r['unit']} {r['date']}"
        if r["unit"] not in units:
            problems.append(f"{where}: unknown unit")
        if r["source"] not in sources:
            problems.append(f"{where}: unknown source {r['source']!r}")
        if r["assumed"] not in ASSUMED:
            problems.append(f"{where}: unknown assumed {r['assumed']!r}")
        cites = [c.strip() for c in r["ref"].split(";") if c.strip()]
        if not cites:
            problems.append(f"{where}: no citation")
        try:
            date.fromisoformat(r["date"])
        except ValueError:
            problems.append(f"{where}: bad date")
        p = places.get(r["place"]) if r["place"] else None
        if r["place"] and not p:
            problems.append(f"{where}: unknown place {r['place']!r}")
        if (r.get("last_day") or "") not in ("", "yes"):
            problems.append(f"{where}: last_day must be empty or yes")
        rows.append({"id": i, "unit": r["unit"], "part": r["part"], "date": r["date"], "station": r["station"],
                     "last_day": r.get("last_day") == "yes",
                     "place": r["place"] or None, "lat": p["lat"] if p else None, "lon": p["lon"] if p else None,
                     "source": r["source"], "assumed": r["assumed"], "note": r["note"],
                     "links": [link(c) for c in cites], "family": own(r)})
    return rows


def load_voyages(voyages_csv, positions_csv, rows, link, problems):
    """The ships (voyages.csv), with the positions they logged on the way (voyage_positions.csv)."""
    positions = {}
    for p in positions_csv:
        key = (p["unit"], p["from_date"])
        try:
            lat = parse_coord(p["lat_fix"] or p["lat"])
            lon = parse_coord(p["lon_fix"] or p["lon"])
        except ValueError as e:
            problems.append(f"voyage_positions.csv: {key} {p['seq']}: can't read {e}")
            continue
        if p["zone"] not in ZONE_HOURS:
            problems.append(f"voyage_positions.csv: {key} {p['seq']}: unknown zone {p['zone']!r}")
            continue
        utc = datetime.fromisoformat(f"{p['date']}T{p['time'][:2]}:{p['time'][2:]}") - timedelta(hours=ZONE_HOURS[p["zone"]])
        positions.setdefault(key, []).append({
            "seq": int(p["seq"]), "date": p["date"], "time": p["time"], "zone": p["zone"], "lat": lat, "lon": lon,
            "as_typed": f"{p['lat']}, {p['lon']}", "fixed": bool(p["lat_fix"] or p["lon_fix"]),
            "on_track": p["on_track"] != "no", "fix_note": p["fix_note"], "utc": utc.strftime("%Y-%m-%dT%H:%MZ"),
            "links": [link(c.strip()) for c in p["ref"].split(";") if c.strip()]})
    voyages = []
    for v in voyages_csv:
        where = f"voyages.csv: {v['unit']} {v['part']} {v['from_date']}"
        if v["status"] not in VOYAGE_STATUS:
            problems.append(f"{where}: unknown status {v['status']!r}")
        ends = [next((r for r in rows if r["unit"] == v["unit"] and r["date"] == d and not r["family"]), None)
                for d in (v["from_date"], v["to_date"])]
        if None in ends:
            problems.append(f"{where}: from_date/to_date must be dates of the unit's stations")
            continue
        pts = sorted(positions.pop((v["unit"], v["from_date"]), []), key=lambda p: p["seq"])
        track = [ends[0]] + [p for p in pts if p["on_track"]] + [ends[1]]
        for a, b in zip(track, track[1:]):
            ta = a.get("utc") or f"{a['date']}T12:00Z"
            tb = b.get("utc") or f"{b['date']}T12:00Z"
            hours = (datetime.fromisoformat(tb.replace("Z", "+00:00")) - datetime.fromisoformat(ta.replace("Z", "+00:00"))).total_seconds() / 3600
            d = km(a, b)
            if a.get("utc") and b.get("utc") and hours > 0 and d / hours > MAX_KNOTS * 1.852:
                problems.append(f"{where}: {d / 1.852:.0f} miles in {hours:.0f} h between logged positions {a['seq']} and {b['seq']}")
        voyages.append({k: v[k] for k in ("unit", "part", "from_date", "to_date", "sailed", "arrived", "from_place",
                                          "to_place", "ships", "status", "carried", "note")}
                       | {"links": [link(c.strip()) for c in v["ref"].split(";") if c.strip()], "positions": pts,
                          "from_id": ends[0]["id"], "to_id": ends[1]["id"]})
    for key in positions:
        problems.append(f"voyage_positions.csv: {key}: no voyage in voyages.csv sails on that date")
    return voyages


def part_lines(parts_csv, rows, units, problems):
    """Each part's line (its own rows, joined to its parent's place before it split off and after it
    ended), and the battalion's own line, broken where it was in parts: [{unit, part, ids}]."""
    pdefs = {(r["unit"], r["part"]): r for r in parts_csv}
    placed = [r for r in rows if r["lat"] is not None and not r["family"]]

    def timeline(unit, part):
        if part == "battalion":
            return [r for r in placed if r["unit"] == unit and r["part"] == "battalion"]
        p = pdefs[(unit, part)]
        up = timeline(unit, p["parent"])
        own = [r for r in placed if r["unit"] == unit and r["part"] == part and p["from"] <= r["date"] <= p["to"]]
        return [r for r in up if r["date"] < p["from"]] + own + [r for r in up if r["date"] >= p["to"]]

    parts = []
    for unit in units:
        run = []
        for r in timeline(unit, "battalion"):
            if run and any(p["unit"] == unit and run[-1]["date"] < p["to"] and p["from"] < r["date"] for p in pdefs.values()):
                parts.append({"unit": unit, "part": "battalion", "ids": [x["id"] for x in run]})
                run = []
            run.append(r)
        parts.append({"unit": unit, "part": "battalion", "ids": [x["id"] for x in run]})
        for (u, part), p in pdefs.items():
            if u != unit:
                continue
            seq = timeline(unit, part)
            own = [r for r in seq if r["part"] == part]
            before = [r for r in seq if r["date"] < p["from"]][-1:]
            after = [r for r in seq if r["date"] >= p["to"]][:1]
            parts.append({"unit": unit, "part": part, "ids": [r["id"] for r in before + own + after]})
    for (u, part) in pdefs:
        if not any(r["unit"] == u and r["part"] == part for r in rows):
            problems.append(f"parts.csv: {u} {part} has no stations")
    for r in rows:
        if not r["family"] and r["part"] != "battalion" and (r["unit"], r["part"]) not in pdefs:
            problems.append(f"stations.csv: {r['unit']} {r['date']}: part {r['part']!r} isn't in parts.csv")
    return [p for p in parts if len(p["ids"]) > 1]


def check_speeds(ids, rows, problems, label=""):
    """No leg faster than MAX_KM_PER_DAY unless the arriving row's note says it went by train."""
    for a, b in zip(ids, ids[1:]):
        ra, rb = rows[a], rows[b]
        days = max((date.fromisoformat(rb["date"]) - date.fromisoformat(ra["date"])).days, 1)
        d = km(ra, rb)
        if d / days > MAX_KM_PER_DAY and "by train" not in rb["note"].lower():
            problems.append(f"too fast{label}: {ra['date']} {ra['place']} -> {rb['date']} {rb['place']}: "
                            f"{d:.0f} km in {days} days")


def load_weather(problems, hint="python3 tools/fetch_station_weather.py seabees"):
    """Daily weather at each station's place (tools/fetch_station_weather.py), by unit|place|date,
    as a list in WEATHER_FIELDS order."""
    path = SEABEES / "weather.csv"
    if not path.exists():
        problems.append(f"no records/seabees/weather.csv: run {hint}")
        return {}
    num = lambda v: float(v) if v not in ("", None) else None
    return {f"{w['unit']}|{w['place']}|{w['date']}": [
        num(w["era5_tmax_c"]), num(w["era5_tmin_c"]), num(w["era5_precip_mm"]), num(w["era5_wind_max_kn"]),
        w["isd_station"] or None, w["isd_name"].title() or None, num(w["isd_km"]), num(w["isd_obs"]),
        num(w["isd_tmax_c"]), num(w["isd_tmin_c"]), num(w["isd_wind_mean_kn"]), num(w["isd_wind_max_kn"]),
        num(w["isd_precip_reports"])] for w in csv.DictReader(path.open())}


PROJECTS = SEABEES / "projects"
PROJECT_FIELDS = {"id", "title", "unit", "part", "places", "from", "from_basis", "to", "to_basis", "dates_ref",
                  "built", "sources"}
BASIS = ("reported", "derived", "inferred", "assumed")
PRECISION = ("exact", "town", "harbour", "island", "peninsula", "area")
EVIDENCE = {"Record.": "record", "Secondary.": "secondary", "Inference.": "inference", "Not known.": "not known"}
SEGMENT = re.compile(r"\[\[cite:([^\]]+)\]\]|\*([^*]+)\*")


def split_markdown(path):
    """A Markdown file -> (front matter, [{heading, paras: [text]}]); paragraphs are separated by a blank line."""
    m = re.match(r"---\n(.*?)\n---\n?(.*)", path.read_text(encoding="utf-8"), re.S)
    if not m:
        return {}, []
    out = []
    for block in re.split(r"\n\s*\n", m.group(2).strip()):
        block = " ".join(ln.strip() for ln in block.strip().splitlines())
        if block.startswith("## "):
            out.append({"heading": block[3:].strip(), "paras": []})
        elif block:
            if not out:
                out.append({"heading": "", "paras": []})
            out[-1]["paras"].append(block)
    return yaml.safe_load(m.group(1)) or {}, out


def segments(text, link):
    """A paragraph -> [["t", text] | ["i", italic] | ["c", citation link]], and the citations in it."""
    segs, cites, at = [], [], 0
    for m in SEGMENT.finditer(text):
        if m.start() > at:
            segs.append(["t", text[at:m.start()]])
        if m.group(1):
            cites.append(m.group(1))
            segs.append(["c", link(m.group(1))])
        else:
            segs.append(["i", m.group(2)])
        at = m.end()
    if at < len(text):
        segs.append(["t", text[at:]])
    return segs, cites


def load_projects(units, parts_csv, places, link, problems):
    """The battalions' main construction projects (records/seabees/projects/<id>.md, one each) and the other stations
    (projects/also-at.md), checked: fields, dates, places, a citation on every paragraph of what was built, and an
    evidence label (record, secondary, inference, not known) on every paragraph of what came afterwards."""
    parts = {(r["unit"], r["part"]) for r in parts_csv}
    projects, also = [], {}
    if not PROJECTS.exists():
        return projects, also

    def day(v, where):
        try:
            return date.fromisoformat(str(v)).isoformat()
        except ValueError:
            problems.append(f"{where}: bad date {v!r}")
            return str(v)

    def cites_of(v, where):
        refs = v if isinstance(v, list) else [v] if v else []
        if not refs:
            problems.append(f"{where}: no citation")
        return [link(str(c)) for c in refs]

    for path in sorted(PROJECTS.glob("*.md")):
        where = f"projects/{path.name}"
        fm, secs = split_markdown(path)
        if path.name == "also-at.md":
            rows = []
            for s in fm.get("stations", []):
                w = f"{where}: {s.get('place')}"
                if s.get("station") and s["station"] not in places:
                    problems.append(f"{w}: unknown station place {s['station']!r}")
                p = places.get(s.get("station"))
                rows.append({"place": s.get("place"), "station": s.get("station"), "what": s.get("what", ""),
                             "from": day(s.get("from"), w), "to": day(s.get("to"), w),
                             "lat": p["lat"] if p else None, "lon": p["lon"] if p else None,
                             "links": cites_of(s.get("ref"), w)})
            if fm.get("unit") not in units:
                problems.append(f"{where}: unknown unit {fm.get('unit')!r}")
            also[fm.get("unit")] = sorted(rows, key=lambda r: r["from"])
            continue
        for k in sorted(set(fm) - PROJECT_FIELDS):
            problems.append(f"{where}: unknown field {k!r}")
        for k in sorted(PROJECT_FIELDS - set(fm)):
            problems.append(f"{where}: missing field {k!r}")
        if fm.get("id") != path.stem:
            problems.append(f"{where}: id must be the file's name")
        if fm.get("unit") not in units:
            problems.append(f"{where}: unknown unit {fm.get('unit')!r}")
        if fm.get("part") != "battalion" and (fm.get("unit"), fm.get("part")) not in parts:
            problems.append(f"{where}: part {fm.get('part')!r} isn't in parts.csv")
        d0, d1 = day(fm.get("from"), where), day(fm.get("to"), where)
        if d1 < d0:
            problems.append(f"{where}: to is before from")
        for k in ("from_basis", "to_basis"):
            if fm.get(k) not in BASIS:
                problems.append(f"{where}: {k} must be one of {', '.join(BASIS)}")
        pls = []
        for p in fm.get("places") or []:
            w = f"{where}: {p.get('name')}"
            if not isinstance(p.get("lat"), (int, float)) or not isinstance(p.get("lon"), (int, float)):
                problems.append(f"{w}: lat/lon must be numbers")
            if p.get("precision") not in PRECISION:
                problems.append(f"{w}: precision must be one of {', '.join(PRECISION)}")
            if p.get("station"):
                s = places.get(p["station"])
                if not s:
                    problems.append(f"{w}: unknown station place {p['station']!r}")
                elif abs(s["lat"] - p["lat"]) > 0.05 or abs(s["lon"] - p["lon"]) > 0.05:
                    problems.append(f"{w}: lat/lon differ from places.csv's {p['station']}")
            elif not p.get("placed"):
                problems.append(f"{w}: needs a station (places.csv) or a note on how it was placed")
            pls.append({k: p.get(k) for k in ("name", "lat", "lon", "precision", "station", "placed")})
        if not pls:
            problems.append(f"{where}: no places")
        listed = {str(c) for c in (fm.get("sources") or []) + (fm.get("dates_ref") or [])}
        out_secs = {}
        for sec in secs:
            name = sec["heading"].lower()
            if name not in ("built", "afterwards"):
                problems.append(f"{where}: unknown section {sec['heading']!r} (Built, Afterwards)")
                continue
            paras = []
            for text in sec["paras"]:
                ev = None
                if name == "afterwards":
                    m = re.match(r"^\*(Record\.|Secondary\.|Inference\.|Not known\.)\*\s*", text)
                    if not m:
                        problems.append(f"{where}: an Afterwards paragraph must start *Record.*, *Secondary.*, "
                                        f"*Inference.* or *Not known.*: {text[:50]!r}")
                    else:
                        ev, text = EVIDENCE[m.group(1)], text[m.end():]
                segs, cites = segments(text, link)
                if not cites and ev != "not known":
                    problems.append(f"{where}: a paragraph with no citation: {text[:50]!r}")
                for c in cites:
                    if c not in listed:
                        problems.append(f"{where}: {c} is cited in the text but not in sources")
                paras.append({"evidence": ev, "segs": segs})
            out_secs["account" if name == "built" else name] = paras
        for k in ("account", "afterwards"):
            if not out_secs.get(k):
                problems.append(f"{where}: no {'Built' if k == 'account' else 'Afterwards'} section")
        projects.append({"id": fm.get("id"), "title": fm.get("title"), "unit": fm.get("unit"), "part": fm.get("part"),
                         "places": pls, "from": d0, "from_basis": fm.get("from_basis"), "to": d1,
                         "to_basis": fm.get("to_basis"), "dates_links": cites_of(fm.get("dates_ref"), where),
                         "built": [str(b) for b in fm.get("built") or []],
                         "sources": cites_of(fm.get("sources"), where), **out_secs})
    projects.sort(key=lambda p: (p["unit"], p["from"]))
    return projects, also


def check_projects():
    """For tools/check_sources.py: the projects' problems, and every citation they make."""
    problems, cited = [], []
    base = citation_links(problems)

    def link(c):
        cited.append(c)
        return base(c)
    units = {r["unit"]: r for r in read_csv(SEABEES / "units.csv")}
    places = load_places(read_csv(SEABEES / "places.csv"), problems)
    load_projects(units, read_csv(SEABEES / "parts.csv"), places, link, problems)
    return problems, cited


def main():
    problems = []
    link = citation_links(problems)
    units = {r["unit"]: {"name": r["name"], "note": r["note"]} for r in read_csv(SEABEES / "units.csv")}
    places = load_places(read_csv(SEABEES / "places.csv"), problems)
    rows = load_stations(read_csv(SEABEES / "stations.csv"), units, places, link, problems)
    voyages = load_voyages(read_csv(SEABEES / "voyages.csv"), read_csv(SEABEES / "voyage_positions.csv"),
                           rows, link, problems)
    parts = part_lines(read_csv(SEABEES / "parts.csv"), rows, units, problems)
    for p in parts:
        check_speeds(p["ids"], rows, problems, f" ({p['unit']} {p['part']})")
    pdefs = {(r["unit"], r["part"]): r for r in read_csv(SEABEES / "parts.csv")}
    for p in parts:   # when each part existed, and what it was
        d = pdefs.get((p["unit"], p["part"]))
        p.update({k: d[k] for k in ("parent", "from", "to", "note")} if d else {})
    projects, also_at = load_projects(units, read_csv(SEABEES / "parts.csv"), places, link, problems)
    out = {"units": units, "places": places, "rows": [{k: v for k, v in r.items() if k != "family"} for r in rows],
           "parts": parts, "voyages": voyages, "projects": projects, "also_at": also_at,
           "weather_fields": WEATHER_FIELDS, "weather": load_weather(problems)}
    path = SEABEES / "seabees.json"
    path.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")) + "\n")
    for p in problems:
        print("PROBLEM:", p)
    print(f"wrote {path.relative_to(RECORDS.parent)}: {len(units)} units, {len(rows)} stations, {len(parts)} lines, "
          f"{len(voyages)} voyages, {len(projects)} projects, {len(problems)} problems")
    sys.exit(1 if problems else 0)


